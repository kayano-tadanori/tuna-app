def apply_meaning_edits(d):
    by_id = {}
    for r in gc.iter_daimon(d, grade="5", app_courses=["sairei"]):
        by_id[r["x"].get("id")] = r["x"]

    applied = 0
    already = 0
    for id_, step_i, old, new in MEANING_EDITS:
        x = by_id.get(id_)
        if x is None:
            raise SystemExit("id not found: %s" % id_)
        steps = x.get("steps") or []
        if step_i >= len(steps):
            raise SystemExit("step index out of range: %s step%d" % (id_, step_i))
        cur = steps[step_i].get("meaning")
        if cur == new:
            already += 1
            continue
        if cur != old:
            raise SystemExit(
                "mismatch at %s step%d: current meaning does not match expected old text.\n"
                "--- current ---\n%s\n--- expected old ---\n%s" % (id_, step_i, cur, old)
            )
        steps[step_i]["meaning"] = new
        applied += 1
    return applied, already


def main():
    d = json.load(io.open(TARGET, encoding="utf-8"))

    m_applied, m_already = apply_meaning_edits(d)

    print("meaning: applied=%d already=%d total=%d" % (m_applied, m_already, len(MEANING_EDITS)))

    io.open(TARGET, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))


if __name__ == "__main__":
    main()
