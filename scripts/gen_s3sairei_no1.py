def _box(s, cx, cy, w, h, label, size=13, col=COL_LINE):
    s.b.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="%s" stroke-width="2" rx="3"/>'
                % (cx - w / 2.0, cy - h / 2.0, w, h, col))
    s.text((cx, cy), label, col, size)


def _brace(s, x1, x2, y, label, up=True, h=26, col=COL_GIVEN, size=13):
    mx = (x1 + x2) / 2.0
    my = y - h if up else y + h
    s.b.append('<path d="M %.1f %.1f Q %.1f %.1f %.1f %.1f" fill="none" stroke="%s" stroke-width="1.6"/>'
                % (x1, y, mx, my, x2, y, col))
    s.text((mx, my - 10 if up else my + 20), label, col, size)


def _house(s, x, y, size=18, col=COL_LINE):
    u"""家のアイコン（三角の屋根＋四角）"""
    s.poly([(x - size, y), (x, y - size), (x + size, y)], col)
    s.b.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="%s" stroke-width="2"/>'
                % (x - size * 0.6, y, size * 1.2, size * 0.75, col))


def step_outline(blocks, x0, y0, scale):
    u"""blocks=[(はば,たか),...] を同じ底辺に すきまなく並べた 段差の輪かく（左下→上→…→右下）"""
    pts = [(x0, y0)]
    x = x0
    for w, h in blocks:
        x2 = x + w * scale
        yt = y0 - h * scale
        pts.append((x, yt)); pts.append((x2, yt))
        x = x2
    pts.append((x, y0))
    return pts


