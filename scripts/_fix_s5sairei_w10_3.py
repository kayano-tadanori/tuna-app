    applied = 0
    already = 0
    for id_, step_i, old, new in SVG_EDITS:
        x = by_id.get(id_)
        if x is None:
            raise SystemExit("id not found: %s" % id_)
        if step_i is None:
            cur = x.get("svg")
            if cur == new:
                already += 1
                continue
            if cur != old:
                raise SystemExit(
                    "mismatch at %s (daimon svg): current svg does not match expected old text.\n"
                    "--- current ---\n%s\n--- expected old ---\n%s" % (id_, cur, old)
                )
            x["svg"] = new
            applied += 1
        else:
            steps = x.get("steps") or []
            cur = steps[step_i].get("svg")
            if cur == new:
                already += 1
                continue
            if cur != old:
                raise SystemExit(
                    "mismatch at %s step%d (svg): current svg does not match expected old text.\n"
                    "--- current ---\n%s\n--- expected old ---\n%s" % (id_, step_i, cur, old)
                )
            steps[step_i]["svg"] = new
            applied += 1
    return applied, already


