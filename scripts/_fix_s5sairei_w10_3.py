def _check_new_svg_gaps():
    board_l, board_r = 20, 620
    panel_w = 72
    starts = [60, 172, 284, 396, 508]
    gaps = [starts[0] - board_l]
    for i in range(len(starts) - 1):
        gaps.append(starts[i + 1] - (starts[i] + panel_w))
    gaps.append(board_r - (starts[-1] + panel_w))
    assert len(gaps) == 6, gaps
    assert all(g == 40 for g in gaps), gaps  # 40px = 20cm（スケール2px/cm）
    assert len(starts) * panel_w + sum(gaps) == board_r - board_l


