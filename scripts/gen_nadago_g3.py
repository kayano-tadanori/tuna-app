    #   原簿の図が見せているのは「100のつぎが1にもどる」ところだけなので、
    #   その部分だけを上のほうに広げて置く
    import math as _m
    cx, cy, R = 112.0, 118.0, 74.0
    body = ['<circle cx="%.0f" cy="%.0f" r="%.0f" fill="none" stroke="%s" stroke-width="1.6"/>'
            % (cx, cy, R, GRAY)]
