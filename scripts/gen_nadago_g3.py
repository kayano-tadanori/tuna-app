    for i, s in enumerate(labs):
        deg = 90 + (2.5 - i) * 17          # 上のあたりに 17°おきに広げる
        a = _m.radians(deg)
        x, y = cx + (R + 16) * _m.cos(a), cy - (R + 16) * _m.sin(a)
        c = RED if s in ("1", "3") else INK
