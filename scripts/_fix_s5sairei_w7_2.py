# HG-6728・6729 と同じように、見本と(1)の図を1枚に合わせて小問側に入れる。
SVG_MARK = "見本（この書き方で数を表します）"


def _svg_inner(svg):
    m = re.match(r"\s*<svg[^>]*>(.*)</svg>\s*$", svg, re.S)
    if not m:
        raise SystemExit("SVGの形が想定とちがう")
    body = m.group(1)
    defs = "".join(re.findall(r"<defs>.*?</defs>", body, re.S))
    body = re.sub(r"<defs>.*?</defs>", "", body, flags=re.S)
    return defs, body.strip("\n")


def _compose_6730(chain, step):
    d1, b1 = _svg_inner(chain)
    d2, b2 = _svg_inner(step)
    return ('<svg viewBox="0 0 310 436" xmlns="http://www.w3.org/2000/svg" '
            'style="display:block;margin:0 auto;max-width:100%;height:auto">\n'
            + d1 + d2 + "\n"
            + '<text x="155" y="16" font-size="14" fill="#e8ecf5" text-anchor="middle">' + SVG_MARK + "</text>\n"
            + '<g transform="translate(0,24)">\n' + b1 + "\n</g>\n"
            + '<line x1="10" y1="228" x2="300" y2="228" stroke="#4f9eff" stroke-width="1" stroke-dasharray="4 4"/>\n'
            + '<text x="155" y="250" font-size="14" fill="#e8ecf5" text-anchor="middle">(1)の図</text>\n'
            + '<g transform="translate(25,258)">\n' + b2 + "\n</g>\n</svg>")


def _rects(svgtext):
    out = []
    for m in re.finditer(r"<rect ([^>]*)/>", svgtext):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        if "x" not in a:
            continue
        out.append((float(a["x"]), float(a["y"]), a.get("fill", "none") != "none"))
    return out


def _read_7shin(rects, ncols, weights):
    """1行に1マスだけぬる7進法の図を読む。ぬった列が右から何番目か＝その位の数。"""
    ys = sorted(set(r[1] for r in rects))
    if len(ys) != len(weights):
        raise SystemExit("行数が想定とちがう: %d" % len(ys))
    val = 0
    for ri, y in enumerate(ys):
        row = sorted([r for r in rects if r[1] == y], key=lambda r: r[0])
        if len(row) != ncols:
            raise SystemExit("列数が想定とちがう: %d" % len(row))
        filled = [i for i, r in enumerate(row) if r[2]]
        if len(filled) > 1:
            raise SystemExit("1行に2マス以上ぬられている")
        val += (0 if not filled else (ncols - filled[0])) * weights[ri]
    return val


