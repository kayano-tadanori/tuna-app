def _assert_edits_unique():
    seen = set()
    for did, where, idx, old, new in EDITS:
        key = (did, where, idx)
        assert key not in seen, "EDITS の中で %r を2回ねらっている" % (key,)
        seen.add(key)


def main():
    _assert_edits_unique()
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    d = json.load(io.open(path, encoding="utf-8"))

    index = {}
    for r in iter_daimon(d, "5", ["sairei"]):
        x = r["x"]
        if x.get("id"):
            index[x["id"]] = x

    changed, already = 0, 0
    touched = set()

    # --- 図（先に検算し、通らなければ1件も書かずに止める） ---
    x = index.get("hd5s_14k1_3")
    if x is None:
        raise SystemExit("hd5s_14k1_3 が見つからない")
    st = x["steps"][0]
    if SVG_MARK in st.get("svg", ""):
        already += 1
    else:
        if not x.get("svg"):
            raise SystemExit("hd5s_14k1_3 に大問の図（見本）が無い")
        _verify_6730(x["svg"], st["svg"])          # 合わなければここで止まる
        st["svg"] = _compose_6730(x["svg"], st["svg"])
        changed += 1
        touched.add("hd5s_14k1_3")

    # --- 文言 ---
    for did, where, idx, old, new in EDITS:
        x = index.get(did)
        if x is None:
            raise SystemExit("%s が見つからない" % did)
        if where == "intro":
            cur = x.get("intro", "")
        else:
            st = x["steps"][idx - 1]
            cur = st.get(where, "")
        if cur == new:
            already += 1
            continue
        assert cur == old, "%s %s#%d の中身が想定とちがう: %r" % (did, where, idx, cur[:60])
        if where == "intro":
            x["intro"] = new
        else:
            x["steps"][idx - 1][where] = new
        changed += 1
        touched.add(did)

    io.open(path, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))
    print("直した欄: %d ／ すでに直っていた欄: %d" % (changed, already))
    print("さわった大問(%d): %s" % (len(touched), " ".join(sorted(touched))))


if __name__ == "__main__":
    main()
