# ── 書きこみ ──────────────────────────────────────────
def main():
    path = os.path.join(BASE, "data", "hama_daimon.json")
    d = json.load(io.open(path, encoding="utf-8"))
    nq = 0
    added = 0
    for gid, course, obj in D:
        node = d["grades"][gid].setdefault(course, {}).setdefault("kokai", {})
        arr = node.setdefault(MONTH, [])
        arr[:] = [x for x in arr if x.get("id") != obj["id"]]
        arr.append(obj)
        added += 1
        nq += len(obj["steps"])
        print("  %-22s %-9s %2d問  図%d枚  %s" % (
            obj["id"], obj["src"], len(obj["steps"]),
            (1 if obj["svg"] else 0) + sum(1 for s in obj["steps"] if s.get("svg")),
            obj["title"]))
    print("\n入れた大問: %d本 / %d問" % (added, nq))
    if "--write" in sys.argv:
        io.open(path, "w", encoding="utf-8").write(
            json.dumps(d, ensure_ascii=False, indent=1))
        print("書きこみました:", path)
    else:
        print("（--write を付けると書きこみます）")


main()
