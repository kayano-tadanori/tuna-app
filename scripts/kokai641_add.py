# ── 原簿から図SVGを取る ──────────────────────────────────
def genbo_svgs(hg):
    """{小問キー: svg} を返す。キー0＝大問ぜんぶで1枚。"""
    g = genbo_svgs._g
    i = g.index(u"### 【%s】" % hg)
    j = g.find(u"\n### 【", i + 5)
    rec = g[i:j if j > 0 else len(g)]
    out = {}
    for m in re.finditer(r"^- 図SVG([^\n:]*):[ \t]*(.*)$", rec, re.M):
        head, rest = m.group(1), m.group(2).strip()
        km = re.search(r"[（(](\d+)[）)]", head)
        key = int(km.group(1)) if km else 0
        if rest:
            # `…` の中だけを取る（後ろに注記が続く書き方があるため）
            bq = re.match(r"`(.*?)`", rest, re.S)
            body = (bq.group(1) if bq else rest.strip("`")).strip()
        else:
            bm = re.match(r"\n```(?:html)?\n(.*?)\n```", rec[m.end():], re.S)
            body = bm.group(1).strip() if bm else ""
        if body and body != u"判読不能":
            out[key] = body
    return out


genbo_svgs._g = io.open(P.find_genbo(), encoding="utf-8").read()


def S(hg, key=0):
    v = genbo_svgs(hg)
    return v.get(key, "")


def q(question, answer, meaning, choices=None, svg=""):
    st = {"question": question, "answer": answer, "meaning": meaning}
    if choices:
        st["choices"] = choices
    if svg:
        st["svg"] = svg
    return st


