def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "data", "hama_daimon.json")

    d = json.load(io.open(path, encoding="utf-8"))

    # ★大問id→大問dict の対応は iter_daimon だけで作る。ついでに全体の
    #   本数・idの集合を「触る前」として控えておき、最後に突き合わせる。
    before_ids = []
    by_id = {}
    for r in iter_daimon(d):
        x = r["x"]
        xid = x.get("id")
        before_ids.append(xid)
        if xid in TARGET_IDS:
            by_id[xid] = x

    missing = TARGET_IDS - set(by_id)
    if missing:
        raise SystemExit("大問idが見つからない（構成が変わった？）: %s" % sorted(missing))

    applied, skipped = [], []
    for xid, step_idx, old, new in FIXES:
        x = by_id[xid]
        steps = x.get("steps", [])

        # ちょうど1回だけ一致することを確認してから直す（1件も無ければ、
        # 既に直したあとの文言に一致しているかを見て冪等に振る舞う）。
        hits = [i for i, s in enumerate(steps) if s.get("meaning") == old]
        if len(hits) == 1:
            assert hits[0] == step_idx, (
                "%s: 見つかった位置(%d)が想定(%d)とちがう" % (xid, hits[0], step_idx))
            steps[step_idx]["meaning"] = new
            applied.append((xid, step_idx))
            continue
        if len(hits) > 1:
            raise SystemExit("%s: 直す前の文言が2回以上一致した（想定外）" % xid)

        # 直す前の文言が無い → 既に新しい文言になっているかを確認する（冪等）
        cur = steps[step_idx].get("meaning", "")
        if cur == new:
            skipped.append((xid, step_idx))
            continue
        raise SystemExit(
            "%s のstep[%d]の文言が想定外（直す前・直したあとのどちらとも一致しない）。"
            "先に最新のJSONを読み直したか確認すること。" % (xid, step_idx))

    # ★書き換えたのは対象の大問だけで、大問の本数・id集合はそもそも変えていない
    #   ことを確認する（このスクリプトは中身の文字列しか触らない設計だが、
    #   念のため iter_daimon で数え直して突き合わせる）。
    after_ids = [r["x"].get("id") for r in iter_daimon(d)]
    assert before_ids == after_ids, "大問の並び・本数が変わってしまった（想定外）"

    out = json.dumps(d, ensure_ascii=False, indent=1)
    io.open(path, "wb").write(out.encode("utf-8"))

    print("適用: %d件 %s" % (len(applied), applied))
    print("スキップ(既に適用済み): %d件 %s" % (len(skipped), skipped))
    print("大問の総数: %d本（変化なし）" % len(after_ids))


if __name__ == "__main__":
    main()
