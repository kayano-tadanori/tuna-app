def P(x, y, dist, deg):
    return (x + dist * math.cos(D(deg)), y - dist * math.sin(D(deg)))


def inner_arc(v, a, b):
    """頂点vで、辺v→aとv→bのはさむ「小さいほうの角」の (始まり, 終わり) を返す。"""
    d1 = math.degrees(math.atan2(-(a[1] - v[1]), a[0] - v[0])) % 360
    d2 = math.degrees(math.atan2(-(b[1] - v[1]), b[0] - v[0])) % 360
    return (d1, d2) if (d2 - d1) % 360 <= 180 else (d2, d1)


def par_mark(x1, y1, x2, y2, n=1, size=7, stroke=HI):
    """平行のしるし（辺の中央に「>」を n 個）。"""
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1.0
    ux, uy = dx / L, dy / L
    nx, ny = -uy, ux
    out = []
    for i in range(n):
        o = (i - (n - 1) / 2.0) * 8
        cx, cy = (x1 + x2) / 2 + ux * o, (y1 + y2) / 2 + uy * o
        out.append(polyline([(cx - ux * size + nx * size * 0.8, cy - uy * size + ny * size * 0.8),
                             (cx + ux * size * 0.6, cy + uy * size * 0.6),
                             (cx - ux * size - nx * size * 0.8, cy - uy * size - ny * size * 0.8)],
                            stroke, 1.6))
    return out


def quad(pts_, ticks=(), pars=(), rights=(), label=None, lab_off=(0, 0)):
    """四角形＋しるし。ticks/pars は辺の番号（0=pts[0]->pts[1]）のリスト。"""
    out = [poly(pts_, LINE, 2)]
    n = len(pts_)
    for i, k in ticks:
        a, b = pts_[i], pts_[(i + 1) % n]
        out += tick_marks(a[0], a[1], b[0], b[1], k, 6)
    for i, k in pars:
        a, b = pts_[i], pts_[(i + 1) % n]
        out += par_mark(a[0], a[1], b[0], b[1], k)
    for i in rights:
        a, b, c = pts_[(i - 1) % n], pts_[i], pts_[(i + 1) % n]
        d1 = math.degrees(math.atan2(-(a[1] - b[1]), a[0] - b[0]))
        d2 = math.degrees(math.atan2(-(c[1] - b[1]), c[0] - b[0]))
        out.append(right_mark(b[0], b[1], d1, d2, 10))
    if label:
        cx = sum(p[0] for p in pts_) / n + lab_off[0]
        cy = sum(p[1] for p in pts_) / n + lab_off[1]
        out.append(t(cx, cy + 5, label, TX, 15))
    return out


