def main():
    errs = verify_svgs()
    if errs:
        print("図SVGの検算に落ちたので 1件も書かずに止めます:")
        for e in errs:
            print("  - " + e)
        return 2

    d = json.load(io.open(PATH, encoding="utf-8"))

    # 対象の大問を id で引く（iter_daimon だけを使う／idがちょうど1回しか出ないことを確かめる）
    found = {}
    for r in iter_daimon(d):
        i = r["x"].get("id")
        if i:
            found.setdefault(i, []).append(r["x"])
    for i in sorted({e[0] for e in EDITS}):
        n = len(found.get(i, []))
        assert n == 1, "大問 %s が %d 件見つかった（ちょうど1件でないので止める）" % (i, n)

    applied, already, touched = 0, 0, set()
    for did, field, idx, old, new in EDITS:
        x = found[did][0]
        if field in ("intro", "svg"):
            cur = x.get(field)
            where = "%s.%s" % (did, field)
        else:
            steps = x.get("steps", [])
            assert 0 <= idx < len(steps), "%s に小問 %d が無い" % (did, idx + 1)
            cur = steps[idx].get(field)
            where = "%s.steps[%d].%s" % (did, idx, field)

        if isinstance(old, str) and old.startswith("md5:"):
            same_old = hashlib.md5((cur or "").encode("utf-8")).hexdigest() == old[4:]
        else:
            same_old = (cur == old)

        if cur == new:
            already += 1
            continue
        assert same_old, (
            "%s のいまの値が old とも new とも合いません（別のセッションが直した可能性）。\n"
            "  いま: %r" % (where, (cur or "")[:160]))

        if field in ("intro", "svg"):
            x[field] = new
        else:
            x["steps"][idx][field] = new
        applied += 1
        touched.add(did)

    io.open(PATH, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))

    print("対象: %s" % PATH)
    print("直した欄: %d ／ すでに直っていた欄: %d ／ 直した大問: %d本" % (applied, already, len(touched)))
    for i in sorted(touched):
        print("  - " + i)
    return 0


if __name__ == "__main__":
    sys.exit(main())
