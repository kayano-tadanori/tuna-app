def verify_svgs():
    """図の座標から数値を出して、問題文と合うかを確かめる。合わなければ理由の一覧を返す。"""
    bad = []

    # --- HG-6711: 表の中身が A=n×n+1 / B=n×3-1 になっているか ---
    texts = re.findall(r'<text x="(\d+)" y="(\d+)"[^>]*>([^<]+)</text>', SVG_6711)
    rows = {}
    for x, y, v in texts:
        rows.setdefault(int(y), []).append((int(x), v))
    for y in (159, 187, 215):
        if y not in rows:
            bad.append("HG-6711: 表の行 y=%d が無い" % y)
    if not bad:
        head = [v for _, v in sorted(rows[159])]
        arow = [v for _, v in sorted(rows[187])]
        brow = [v for _, v in sorted(rows[215])]
        if head[0] != "数" or arow[0] != "A" or brow[0] != "B":
            bad.append("HG-6711: 表の見出しが 数/A/B でない: %r" % [head[0], arow[0], brow[0]])
        else:
            ns = [int(v) for v in head[1:]]
            if ns != [1, 2, 3, 4, 5]:
                bad.append("HG-6711: 表の上の段が1〜5でない: %r" % ns)
            for n, a, b in zip(ns, arow[1:], brow[1:]):
                if int(a) != n * n + 1:
                    bad.append("HG-6711: Aの表 %d→%s（n×n+1なら%d）" % (n, a, n * n + 1))
                if int(b) != n * 3 - 1:
                    bad.append("HG-6711: Bの表 %d→%s（n×3-1なら%d）" % (n, b, n * 3 - 1))
            # 設問の答え（226 と 9）がこの表の規則から出るか
            if not (3 * 15 - 1 == 44 and 15 * 15 + 1 == 226):
                bad.append("HG-6711: (1)の答え226が表の規則と合わない")
            if not (3 * 82 - 1 == 245 and 9 * 9 + 1 == 82):
                bad.append("HG-6711: (2)の答え9が表の規則と合わない")
        if 'x1="130" y1="70"' in SVG_6711:
            bad.append("HG-6711: AからBへ伸びて宙で終わる線が残っている")

    # --- HG-6842: 棒の長さの比が 1/2 と 2/5、差が12cm になっているか ---
    def seg(sv, x):
        m = re.search(r'<line x1="%d" y1="(\d+)" x2="%d" y2="(\d+)"' % (x, x), sv)
        return (int(m.group(1)), int(m.group(2))) if m else None
    a = seg(SVG_6842, 150)
    b = seg(SVG_6842, 280)
    mw = re.search(r'<rect x="\d+" y="(\d+)" width="\d+" height="(\d+)"', SVG_6842)
    if not (a and b and mw):
        bad.append("HG-6842: 棒か水の四角形が図から読み取れない")
    else:
        water_top, water_h = int(mw.group(1)), int(mw.group(2))
        bottom = water_top + water_h
        if a[1] != bottom or b[1] != bottom:
            bad.append("HG-6842: 棒が池の底(y=%d)まで届いていない: A=%r B=%r" % (bottom, a, b))
        la, lb = bottom - a[0], bottom - b[0]   # 棒の全長（px）
        sunk = water_h                          # 水につかった長さ（px）
        if sunk * 2 != la:
            bad.append("HG-6842: Aの沈み %d/%d が 1/2 でない" % (sunk, la))
        if sunk * 5 != lb * 2:
            bad.append("HG-6842: Bの沈み %d/%d が 2/5 でない" % (sunk, lb))
        scale = sunk / 24.0                     # 答えの24cm ぶんが sunk px
        diff_cm = (lb - la) / scale
        if abs(diff_cm - 12.0) > 1e-9:
            bad.append("HG-6842: 2本の長さの差が %.3fcm で、問題文の12cmと合わない" % diff_cm)
        if not re.search(r'<line x1="322" y1="40" x2="322" y2="88"', SVG_6842):
            bad.append("HG-6842: 12cmの縦の寸法線が無い")
        if SVG_6842.count('marker-end="url(#hg6842b)"') != 2:
            bad.append("HG-6842: 12cmの寸法線の矢じりが2つになっていない")
    return bad


