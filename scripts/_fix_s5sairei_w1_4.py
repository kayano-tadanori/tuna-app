def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE, "data", "hama_daimon.json")
    path = os.path.abspath(path)
    print("対象: " + path)

    # ★改行コードとBOMは、読んだときのまま書き戻す。
    #   io.open(..., "w") で書くと Windows では "\n" が "\r\n" に化けて
    #   全125,000行が差分になる（実際にそれで250,570行の差分を出した）。
    with open(path, "rb") as f:
        raw = f.read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    if bom:
        raw = raw[3:]
    crlf = b"\r\n" in raw
    d = json.loads(raw.decode("utf-8"))

    # iter_daimon が唯一の走査口。ここで id -> 大問 の索引をつくる。
    index = {}
    for rec in G.iter_daimon(d):
        x = rec["x"]
        i = x.get("id")
        if i:
            index.setdefault(i, []).append(x)

    changed = {}
    skipped = 0
    added_steps = 0

    def pick(did):
        got = index.get(did)
        assert got, "大問が見つからない: " + did
        assert len(got) == 1, "同じidの大問が%d本ある: %s" % (len(got), did)
        return got[0]

    # --- 欄まるごとの置きかえ
    for did, field, si, old, new in FIELD_EDITS:
        x = pick(did)
        if field == "intro":
            cur = x.get("intro")
            if cur == new:
                skipped += 1
                continue
            assert cur == old, "introが想定と違う（他のセッションが先に直した？）: " + did
            x["intro"] = new
        else:
            steps = x.get("steps") or []
            assert si < len(steps), "小問%dが無い: %s" % (si + 1, did)
            cur = steps[si].get(field)
            if cur == new:
                skipped += 1
                continue
            assert cur == old, "%s の小問%d の %s が想定と違う: %s" % (did, si + 1, field, repr(cur)[:90])
            steps[si][field] = new
        changed[did] = changed.get(did, 0) + 1

    # --- 部分置換（一意であることを必ず確かめる）
    for did, field, si, old, new in SUB_EDITS:
        x = pick(did)
        steps = x.get("steps") or []
        assert si < len(steps), "小問%dが無い: %s" % (si + 1, did)
        cur = steps[si].get(field) or ""
        if new in cur and old not in cur:
            skipped += 1
            continue
        n = cur.count(old)
        assert n == 1, "アンカーが%d回出る（1回でないと置けない）: %s 小問%d" % (n, did, si + 1)
        steps[si][field] = cur.replace(old, new)
        changed[did] = changed.get(did, 0) + 1

    # --- 図への差しこみ
    for did, anchor, addition in SVG_INSERTS:
        x = pick(did)
        svg = x.get("svg") or ""
        assert svg, "図が無い: " + did
        if addition in svg:
            skipped += 1
            continue
        n = svg.count(anchor)
        assert n == 1, "図のアンカーが%d回出る（1回でないと置けない）: %s" % (n, did)
        x["svg"] = svg.replace(anchor, anchor + addition)
        changed[did] = changed.get(did, 0) + 1

    if not changed:
        print("直すところはもう残っていない（すべて適用ずみ）。書き戻しもしない。")
        return 0

    text = json.dumps(d, ensure_ascii=False, indent=1) + "\n"
    if crlf:
        text = text.replace("\n", "\r\n")
    out = text.encode("utf-8")
    if bom:
        out = b"\xef\xbb\xbf" + out
    with open(path, "wb") as f:
        f.write(out)

    for did in sorted(changed, key=lambda k: (len(k), k)):
        print("直した: %-16s %d か所" % (did, changed[did]))
    print("大問 %d 本 ／ のべ %d か所 ／ すでに直っていて飛ばしたもの %d か所 ／ 足した小問 %d"
          % (len(changed), sum(changed.values()), skipped, added_steps))
    print("答えの数値・入力形式は1つも変えていない。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
