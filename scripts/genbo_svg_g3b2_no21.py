def proj(ox, oy, x, y, z, s):
    return (ox + x * s + y * DX * s, oy - z * s + y * DY * s)


def boxdraw(ox, oy, w, h, d, s=1.0, hidden=True, fill=FILL, stroke=LINE, sw=2):
    """(ox,oy)＝手前下の左すみ。w=横, h=高さ, d=おくゆき（画面単位）。"""
    A = lambda x, y, z: (ox + x + y * DX, oy - z + y * DY)
    v = {k: A(*k) for k in [(0, 0, 0), (w, 0, 0), (w, 0, h), (0, 0, h),
                            (0, d, 0), (w, d, 0), (w, d, h), (0, d, h)]}
    out = [poly([v[(0, 0, 0)], v[(w, 0, 0)], v[(w, 0, h)], v[(0, 0, h)]], stroke, sw, fill),
           poly([v[(0, 0, h)], v[(w, 0, h)], v[(w, d, h)], v[(0, d, h)]], stroke, sw, fill),
           poly([v[(w, 0, 0)], v[(w, d, 0)], v[(w, d, h)], v[(w, 0, h)]], stroke, sw, fill)]
    if hidden:
        out += [ln(*v[(0, d, 0)], *v[(w, d, 0)], GRAY, 1.2, "5 4"),
                ln(*v[(0, d, 0)], *v[(0, 0, 0)], GRAY, 1.2, "5 4"),
                ln(*v[(0, d, 0)], *v[(0, d, h)], GRAY, 1.2, "5 4")]
    return out, v


def cubes(ox, oy, cells, s, fill=FILL, stroke=LINE, sw=1.4):
    """小さな立方体のあつまり。cells＝(x,y,z)の集合。y が大きいほど おく。"""
    out = []
    for (x, y, z) in sorted(cells, key=lambda c: (-c[1], c[2], c[0])):
        p = lambda a, b, c: proj(ox, oy, x + a, y + b, z + c, s)
        out += [poly([p(0, 0, 0), p(1, 0, 0), p(1, 0, 1), p(0, 0, 1)], stroke, sw, fill),
                poly([p(0, 0, 1), p(1, 0, 1), p(1, 1, 1), p(0, 1, 1)], stroke, sw, fill),
                poly([p(1, 0, 0), p(1, 1, 0), p(1, 1, 1), p(1, 0, 1)], stroke, sw, fill)]
    return out


