def scan_courses(d):
    """原簿×アプリを突き合わせて、コースごとの結果を返す。

    戻り値:
      rows  … [{grade, course, label, n_genbo, n_daimon, n_toi, miss[]}, ...]
      nohg  … [(grade, course, 大問のid), ...]  原簿番号が付いていない大問

    ★「未収録（miss）」の定義はここ1か所。
      原簿の分母 −（アプリに入っているHG）−（作れないCANNOT）
                −（同じ問題SAME）−（国語側ファイルに入っているKOKUGO_DONE）
    """
    rows, nohg = [], []
    for (grade, course) in sorted(gen):
        node = d["grades"].get(grade, {}).get(APP_COURSE_KEY.get(course, course), {})
        # ★灘合は原簿では算数・理科が同じ「小N灘合」見出しに混ざっているが、
        #   アプリでは nadago（算数）と nadago_rika（理科）に分かれている。
        extra_nodes = []
        if course == "nadago":
            extra_nodes.append(d["grades"].get(grade, {}).get("nadago_rika", {}))
        inapp = set()
        n = q = 0
        for nd in [node] + extra_nodes:
            for kind in KINDS:
                for v in nd.get(kind, {}).values():
                    for x in v:
                        n += 1
                        q += len(x.get("steps", []))
                        h = hgof(x)
                        if h:
                            inapp.update(h)
                        else:
                            nohg.append((grade, course, x.get("id")))
        miss = sorted(gen[(grade, course)] - inapp - set(CANNOT) - set(SAME) - KOKUGO_DONE)
        rows.append({
            "grade": grade, "course": course,
            "label": "小%s%s" % (grade, COURSE_LABEL[course]),
            "n_genbo": len(gen[(grade, course)]), "n_daimon": n, "n_toi": q,
            "miss": miss,
        })
    return rows, nohg
