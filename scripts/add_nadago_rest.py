def count_all(x):
    n = 0
    if isinstance(x, dict):
        if x.get("id") and x.get("steps") is not None:
            n += 1
        for v in x.values():
            n += count_all(v)
    elif isinstance(x, list):
        for v in x:
            n += count_all(v)
    return n


