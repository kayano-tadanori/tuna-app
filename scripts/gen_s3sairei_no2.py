def _circ(s, cx, cy, label, ask=False, r=26):
    col = COL_ASK if ask else COL_LINE
    s.b.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="none" stroke="%s" stroke-width="2.4"/>'
                % (cx, cy, r, col))
    if label is not None:
        s.text((cx, cy), str(label), col, 18)


def tree_sum(rows, ask, w=110, h=110, r=26):
    u"""大問1：rows=ピラミッド全段（上から。1段ごとに1つ短くなる）。各マスはNone(空欄)/数値(あたえられた数)。
       ask=(行,列)で 答えを聞く場所を指定し、そこには rows の値をそのまま ラベルとして表示する（例:"(1)"）"""
    n = len(rows[0])
    W = w * (n - 1) + 60
    H = h * (len(rows) - 1) + 60
    s = Svg(W, H)
    xs = [[30 + w * i for i in range(len(row))] for row in rows]
    maxw = xs[0][-1]
    for row_i in range(len(rows)):
        off = (maxw - xs[row_i][-1]) / 2.0 if xs[row_i] else 0
        xs[row_i] = [x + off for x in xs[row_i]]
    ys = [30 + h * i for i in range(len(rows))]
    for ri in range(len(rows) - 1):
        for ci in range(len(rows[ri]) - 1):
            s.line((xs[ri][ci], ys[ri] + r), (xs[ri + 1][ci], ys[ri + 1] - r), COL_SUB)
            s.line((xs[ri][ci + 1], ys[ri] + r), (xs[ri + 1][ci], ys[ri + 1] - r), COL_SUB)
    for ri, row in enumerate(rows):
        for ci, v in enumerate(row):
            is_ask = (ri, ci) == ask
            s.b.append('<circle cx="%.1f" cy="%.1f" r="%d" fill="#0b1020" stroke="%s" stroke-width="2.4"/>'
                        % (xs[ri][ci], ys[ri], r, COL_ASK if is_ask else COL_LINE))
            if v is not None:
                s.text((xs[ri][ci], ys[ri]), str(v), COL_ASK if is_ask else COL_GIVEN, 18)
    return s.out()


def tree_pair(tops, mids, bottom, ask="bottom"):
    u"""大問2：top4つを(0,1)(2,3)の2組に分け、組ごとの和をmidに、mid2つの和をbottomに。
       ask: 'bottom' か top/midのindex文字列で どこを聞くか"""
    s = Svg(360, 260)
    xs_top = [50, 130, 230, 310]
    xs_mid = [90, 270]
    x_bot = 180
    y_top, y_mid, y_bot = 40, 140, 230
    for i in (0, 1):
        s.line((xs_top[0 + i * 2], y_top + 26), (xs_mid[i], y_mid - 26), COL_SUB)
        s.line((xs_top[1 + i * 2], y_top + 26), (xs_mid[i], y_mid - 26), COL_SUB)
    s.line((xs_mid[0], y_mid + 26), (x_bot, y_bot - 26), COL_SUB)
    s.line((xs_mid[1], y_mid + 26), (x_bot, y_bot - 26), COL_SUB)
    for i, v in enumerate(tops):
        ask_here = (ask == "top%d" % i)
        _circ(s, xs_top[i], y_top, v, ask_here)
    for i, v in enumerate(mids):
        ask_here = (ask == "mid%d" % i)
        _circ(s, xs_mid[i], y_mid, v, ask_here)
    _circ(s, x_bot, y_bot, bottom, ask == "bottom")
    return s.out()


def grid3(vals, size=54, gap=0):
    u"""大問5：3x3の点数マス"""
    s = Svg(size * 3 + 20, size * 3 + 20)
    for r in range(3):
        for c in range(3):
            x, y = 10 + c * size, 10 + r * size
            s.b.append('<rect x="%d" y="%d" width="%d" height="%d" fill="none" stroke="%s" stroke-width="2"/>'
                        % (x, y, size, size, COL_LINE))
            s.text((x + size / 2.0, y + size / 2.0), vals[r][c], COL_GIVEN, 20)
    return s.out()


