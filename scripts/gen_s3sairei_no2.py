def machine_grid(mark=None, vals=None, size=48):
    u"""大問6：3x3のきかい。markはON(1)にするマス、valsは数値を直接指定"""
    s = Svg(size * 3 + 30, size * 3 + 50)
    for i, ch in enumerate(LETTERS):
        r, c = divmod(i, 3)
        x, y = 15 + c * size, 40 + r * size
        on = mark and mark[r][c]
        v = vals[r][c] if vals else (1 if on else 0)
        fill = "#2a3a5c" if on else "none"
        s.b.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" stroke="%s" stroke-width="2"/>'
                    % (x, y, size, size, fill, COL_LINE))
        s.text((x + size / 2.0, y + size / 2.0), str(v), COL_GIVEN if (vals or on) else COL_SUB, 18)
        s.text((x + size / 2.0, y - 8), ch, COL_MARK, 13)
    return s.out()


def moore(vals_press):
    u"""検算用：3x3グリッドに vals_press[(r,c)]=回数 で押したときの各マスの合計を返す"""
    total = [[0, 0, 0] for _ in range(3)]
    for (pr, pc), n in vals_press.items():
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                r, c = pr + dr, pc + dc
                if 0 <= r < 3 and 0 <= c < 3:
                    total[r][c] += n
    return total


