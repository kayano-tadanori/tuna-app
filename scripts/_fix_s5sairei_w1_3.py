def find_daimon(d):
    """id → 大問dict。iter_daimon（唯一の走査口）だけを使う。"""
    out = {}
    for r in gc.iter_daimon(d):
        x = r["x"]
        i = x.get("id")
        if i:
            assert i not in out, "id が重複している: %s" % i
            out[i] = x
    return out


def apply_edits(d, verbose=True):
    idx = find_daimon(d)
    changed_ids, added, skipped, done = set(), 0, 0, 0
    for did, where, old, new, note in EDITS:
        assert did in idx, "大問 %s が見つからない" % did
        x = idx[did]
        kind = where[0]

        if kind == "step":
            _, i, field = where
            assert i < len(x["steps"]), "%s に 小問%d が無い" % (did, i + 1)
            cur = x["steps"][i].get(field, "")
            if cur == new:
                skipped += 1
                continue
            assert cur == old, "%s steps[%d].%s が想定と違う\n  いま: %r\n  想定: %r" % (did, i, field, cur, old)
            x["steps"][i][field] = new

        elif kind in ("intro", "title"):
            cur = x.get(kind, "")
            if cur == new:
                skipped += 1
                continue
            assert cur == old, "%s の %s が想定と違う: %r" % (did, kind, cur)
            x[kind] = new

        elif kind == "svg" and len(where) == 1:
            if x.get("svg") == new:
                skipped += 1
                continue
            assert x.get("svg"), "%s に svg が無い" % did
            x["svg"] = new

        elif kind == "svg" and where[1] == "sub":
            s = x.get("svg", "")
            # ★old が new の一部になっている置換（＝末尾に足すだけの修正）だと
            #   「old がまだ残っている」ので毎回また足してしまう。new があれば済み。
            if new in s:
                skipped += 1
                continue
            n = s.count(old)
            assert n == 1, "%s の図で置きかえ先が %d 回出る（1回でないとだめ）: %r" % (did, n, old)
            x["svg"] = s.replace(old, new)

        elif kind == "svg" and where[1] == "suball":
            want = where[2]
            s = x.get("svg", "")
            if s.count(old) == 0 and s.count(new) >= want:
                skipped += 1
                continue
            n = s.count(old)
            assert n == want, "%s の図で %r が %d 回（%d回のはず）" % (did, old, n, want)
            x["svg"] = s.replace(old, new)

        elif kind == "addstep":
            marker, step = old, new
            if any(marker in st.get("question", "") for st in x["steps"]):
                skipped += 1
                continue
            x["steps"].append(step)
            added += 1

        else:
            raise AssertionError("知らない場所の指定: %r" % (where,))

        changed_ids.add(did)
        done += 1
        if verbose:
            print("  [直した] %-16s %s" % (did, note))
    return changed_ids, done, added, skipped


def main():
    args = [a for a in sys.argv[1:] if a != "--dry"]
    dry = "--dry" in sys.argv[1:]
    path = args[0] if args else os.path.join("data", "hama_daimon.json")
    assert os.path.exists(path), "ファイルが無い: %s" % path

    print("■ 図の検算（入れる前に座標から数値を出して問題文と突き合わせる）")
    print("  18_2  DEF÷ABC = %.3f 倍（原簿の「6倍」は誤り／現物の図の実測も約14）" % check_18_2_svg())
    print("  18_4  四角形EHFC = %.2f cm²（長方形280cm²のうち）" % check_18_4_svg())
    a, p = check_23k1_3_fig1()
    print("  23k1_3(1) 面積 %.2f cm² ／ まわり %.2f cm（解答PDF p21 と一致）" % (a, p))

    raw = io.open(path, "rb").read()
    d = json.loads(raw.decode("utf-8"))
    print("■ 置きかえ（対象 %s）" % path)
    ids, done, added, skipped = apply_edits(d)

    out = json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8") + b"\n"
    print("■ まとめ")
    print("  直した大問 %d本 / 直した箇所 %d / 足した小問 %d / すでに直っていて飛ばした %d"
          % (len(ids), done, added, skipped))
    print("  大問id: %s" % " ".join(sorted(ids)))
    print("  バイト数 %d → %d" % (len(raw), len(out)))
    if dry:
        print("  --dry なので書き戻さない")
        return
    if out == raw:
        print("  中身に変化なし（冪等）＝書き戻さない")
        return
    with io.open(path, "wb") as f:      # ★"w" は不可（CRLFに化ける）
        f.write(out)
    print("  書き戻した: %s" % path)


if __name__ == "__main__":
    main()
