# ---------------------------------------------------------------- 図の検算
def tri_area(p, q, r):
    return abs(p[0] * (q[1] - r[1]) + q[0] * (r[1] - p[1]) + r[0] * (p[1] - q[1])) / 2.0


def poly_area(pts):
    s = 0.0
    for i in range(len(pts)):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % len(pts)]
        s += x1 * y2 - x2 * y1
    return abs(s) / 2.0


def check_18_2_svg():
    """HG-1262 の図：BD=BA×2 / AF=AC×3 / CE=CB×3 を満たし、DEF が ABC の 14倍 になるか。"""
    D = (292.0, 20.0)
    E = (24.0, 22.0)
    F = (150.0, 214.0)
    A = (214.3, 48.1)
    B = (136.6, 76.3)
    C = (192.9, 103.4)
    # 作図の条件そのもの（誤差 0.3px 以内）
    eps = 0.3
    for got, want, name in (
        (D, (2 * A[0] - B[0], 2 * A[1] - B[1]), "D=2A-B (BD=BA×2)"),
        (E, (3 * B[0] - 2 * C[0], 3 * B[1] - 2 * C[1]), "E=3B-2C (CE=CB×3)"),
        (F, (3 * C[0] - 2 * A[0], 3 * C[1] - 2 * A[1]), "F=3C-2A (AF=AC×3)"),
    ):
        assert abs(got[0] - want[0]) < eps and abs(got[1] - want[1]) < eps, \
            "18_2 図の座標が条件を満たさない: %s got=%s want=%s" % (name, got, want)
    ratio = tri_area(*[D, E, F]) / tri_area(A, B, C)
    assert 13.9 < ratio < 14.1, "18_2 図の DEF/ABC が 14 でない: %.3f" % ratio
    # 3つの角の三角形が 3倍・4倍・6倍（解説で使う数）
    base = tri_area(A, B, C)
    for got, want, name in ((tri_area(D, A, F) / base, 3.0, "DAF"),
                            (tri_area(D, B, E) / base, 4.0, "DBE"),
                            (tri_area(F, C, E) / base, 6.0, "FCE")):
        assert abs(got - want) < 0.05, "18_2 図の三角形%s が %.2f 倍（%s倍のはず）" % (name, got, want)
    return ratio


def check_18_4_svg():
    """HG-1264 の図：四角形EHFC が長方形の 64/280 になるか。"""
    x0, y0, w, h = 26.0, 24.0, 196.0, 112.0
    A = (x0, y0)
    B = (x0 + w, y0)
    C = (x0 + w, y0 + h)
    D = (x0, y0 + h)
    E = (B[0], y0 + h * 3 / 5.0)          # BE:EC=3:2
    F = (C[0] - w * 3 / 5.0, C[1])        # CF:FD=3:2
    H = (x0 + w * 2 / 7.0, y0 + h * 5 / 7.0)  # BH:HD=5:2（砂時計の相似）
    assert abs(E[1] - 91.2) < 0.05 and abs(F[0] - 104.4) < 0.05, "18_4 E/F の座標がずれている"
    assert abs(H[0] - 82.0) < 0.05 and abs(H[1] - 104.0) < 0.05, "18_4 H の座標がずれている"
    # H が AF と BD の交点になっているか（両方の直線に乗るか）
    for (p, q) in ((A, F), (B, D)):
        cross = (q[0] - p[0]) * (H[1] - p[1]) - (q[1] - p[1]) * (H[0] - p[0])
        assert abs(cross) < 1.0, "18_4 H が直線に乗っていない cross=%.3f" % cross
    ratio = poly_area([E, H, F, C]) / (w * h)
    assert abs(ratio * 280 - 64) < 0.05, "18_4 斜線部が 64cm² にならない: %.3f cm²" % (ratio * 280)
    return ratio * 280


def check_23k1_3_fig1():
    """HG-3656(1) の図：一辺12cm・半径6cmの60°おうぎ形3つで 54.84cm / 56.52cm² か。"""
    side_px, r_px = 114.0, 57.0          # 図の1辺と弧の半径（px）
    scale = side_px / 12.0               # 1cm = 9.5px（現物：6cm+6cm=12cm）
    assert abs(r_px / scale - 6.0) < 1e-9, "23k1_3 弧の半径が 6cm でない"
    area = 3 * (r_px * r_px * PI * 60 / 360.0) / (scale * scale)
    arc = 3 * (2 * r_px * PI * 60 / 360.0) / scale
    line = 3 * side_px / scale
    assert abs(area - 56.52) < 0.01, "23k1_3(1) 面積が 56.52 にならない: %.4f" % area
    assert abs(arc + line - 54.84) < 0.01, "23k1_3(1) まわりが 54.84 にならない: %.4f" % (arc + line)
    return area, arc + line


