def stick(x, y, cm, label=None, unit=17.0, h=9.0, color=LINE, lab_fill=TX):
    """竹ひご1本（細長い棒）。左はしが(x,y)。"""
    w = cm * unit
    out = [path("M %.1f %.1f L %.1f %.1f Q %.1f %.1f %.1f %.1f L %.1f %.1f "
                "Q %.1f %.1f %.1f %.1f Z" % (
                    x, y + h / 2, x + w, y + h / 2, x + w + 5, y, x + w, y - h / 2,
                    x, y - h / 2, x - 5, y, x, y + h / 2), color, 1.8)]
    if label:
        out.append(t(x + w / 2, y - h / 2 - 7, label, lab_fill, 13))
    return out


