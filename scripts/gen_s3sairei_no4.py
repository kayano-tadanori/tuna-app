def base_grid(weights, rows, digits, letter=None):
    u"""位取りのマス目。weights=各列の重み(左から)。rows=1列あたりのマス数(=底−1)。
       digits=各列で塗るマス数(0〜rows)。letterはア〜ケの記号ラベル（あれば下に書く）"""
    n = len(weights)
    cw, ch = 56, 48
    s = Svg(cw * n + 20, ch * rows + 40)
    for c in range(n):
        x = 10 + c * cw
        for r in range(rows):
            y = 10 + r * ch
            filled = (rows - r) <= digits[c]  # 下づめで塗る
            fill = "#2a3a5c" if filled else "none"
            s.b.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" stroke="%s" stroke-width="2"/>'
                        % (x, y, cw, ch, fill, COL_LINE))
    if letter:
        s.text((cw * n / 2.0 + 10, ch * rows + 28), letter, COL_MARK, 18)
    return s.out()


def digits_of(value, weights):
    u"""weights(大きい順)を使って value を各位の数字に分解する（weightsは連続する累乗）"""
    out = []
    rem = value
    for w in weights:
        d = rem // w
        out.append(d)
        rem -= d * w
    return out


def base_grid_choices(weights, rows, vals, cols=4, cw=34, ch=30):
    u"""ア〜クの8つの図を1枚に並べる。
       ★実物（p024・p026）は選択肢の図が8枚ならんでいる。前は正解の1枚だけを、
         しかも「イ」「キ」と記号入りで出していた＝答えが図に書いてある状態だった"""
    letters = list(vals.keys())
    n = len(weights)
    gw = cw * n + 16
    gh = ch * rows + 26
    rows_n = (len(letters) + cols - 1) // cols
    s = Svg(gw * cols + 10, gh * rows_n + 10)
    for i, L in enumerate(letters):
        gx = 5 + (i % cols) * gw
        gy = 5 + (i // cols) * gh
        digits = digits_of(vals[L], weights)
        for c in range(n):
            x = gx + 8 + c * cw
            for r in range(rows):
                y = gy + 4 + r * ch
                filled = (rows - r) <= digits[c]
                fill = "#2a3a5c" if filled else "none"
                s.b.append('<rect x="%.0f" y="%.0f" width="%d" height="%d" fill="%s" stroke="%s" stroke-width="1.5"/>'
                           % (x, y, cw, ch, fill, COL_LINE))
        s.text((gx + gw / 2.0, gy + ch * rows + 16), L, COL_MARK, 15)
    return s.out()


def dial(cx, cy, r, npos, value, label):
    s_frag = []
    s_frag.append('<circle cx="%d" cy="%d" r="%d" fill="none" stroke="%s" stroke-width="2"/>'
                  % (cx, cy, r, COL_LINE))
    s_frag.append('<text x="%d" y="%d" text-anchor="middle" fill="%s" font-size="16" font-weight="bold">%s</text>'
                  % (cx, cy - r - 14, COL_MARK, label))
    import math
    # ★目もりの数字は円の内がわに置く（実物p027・p028も内がわ）。
    #   外がわ(r+16)に置くと 0の数字がダイヤルの名前(C/B/A)と3pxしか離れず重なり、
    #   右はしのダイヤルでは viewBox(はば360)から はみ出して切れていた
    for p in range(npos):
        ang = -90 + 360.0 * p / npos
        rad = math.radians(ang)
        tx = cx + (r - 14) * math.cos(rad)
        ty = cy + (r - 14) * math.sin(rad) + 5
        s_frag.append('<text x="%.1f" y="%.1f" text-anchor="middle" fill="%s" font-size="13">%d</text>'
                      % (tx, ty, COL_GIVEN, p))
    ang = -90 + 360.0 * value / npos
    rad = math.radians(ang)
    ex = cx + (r - 24) * math.cos(rad)      # はりは目もりの数字より内がわで止める
    ey = cy + (r - 24) * math.sin(rad)
    s_frag.append('<line x1="%d" y1="%d" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="2.5"/>'
                  % (cx, cy, ex, ey, COL_ASK))
    s_frag.append('<circle cx="%d" cy="%d" r="3" fill="%s"/>' % (cx, cy, COL_ASK))
    return s_frag


def machine3(npos, values, labels, entry=u"入口"):
    u"""3つのダイヤル(左から順)。valuesは各ダイヤルの現在値、labelsは文字（例:["C","B","A"]）"""
    s = Svg(360, 200)
    s.b.append('<rect x="10" y="20" width="340" height="150" fill="none" stroke="%s" stroke-width="2"/>' % COL_LINE)
    s.b.append('<rect x="270" y="0" width="80" height="30" fill="none" stroke="%s" stroke-width="2"/>' % COL_LINE)
    s.text((310, 15), entry, COL_LINE, 13)
    cxs = [90, 195, 300]
    for cx, v, lab in zip(cxs, values, labels):
        s.b.extend(dial(cx, 105, 55, npos, v, lab))
    return s.out()


