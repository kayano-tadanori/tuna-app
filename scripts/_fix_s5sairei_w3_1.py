def load(path):
    return json.loads(io.open(path, "rb").read().decode("utf-8"))


def save(path, d):
    # 元ファイルは末尾に改行が1つある。付けないと無変更でも1バイト差が出る。
    body = json.dumps(d, ensure_ascii=False, indent=1) + chr(10)
    io.open(path, "wb").write(body.encode("utf-8"))


def index_by_id(d):
    """id → 大問の dict。走査は iter_daimon だけを使う（自前で入れ子を歩かない）。"""
    out = {}
    for rec in gc.iter_daimon(d):
        x = rec["x"]
        did = x.get("id")
        if did:
            out.setdefault(did, []).append(x)
    return out


def get_holder(x, field, idx):
    """(直す入れもの, キー) を返す。"""
    if field == "intro":
        return x, "intro"
    steps = x.get("steps")
    assert isinstance(steps, list), "steps が無い"
    assert 0 <= idx < len(steps), "小問 %d が無い（%d 問しかない）" % (idx, len(steps))
    key = "question" if field == "question" else "meaning"
    return steps[idx], key


def main(argv):
    path = argv[1] if len(argv) > 1 else DEFAULT_JSON
    assert os.path.exists(path), "見つからない: %s" % path
    d = load(path)
    by_id = index_by_id(d)

    done, skipped = [], []
    for e in EDITS:
        did, field, idx = e["id"], e["field"], e["idx"]
        hits = by_id.get(did, [])
        assert len(hits) == 1, "id %s が %d 本ある（1本でないと引き当てられない）" % (did, len(hits))
        x = hits[0]
        holder, key = get_holder(x, field, idx)
        cur = holder.get(key, "")
        assert isinstance(cur, str), "%s %s%s が文字列でない" % (did, field, idx)

        label = "%s %s%s (%s)" % (did, field, "" if idx is None else "[%d]" % idx, e["tag"])

        # ★冪等の判定は「新しい文字列がすでに入っているか」で見る。
        #   「古い文字列がまだあるか」で見てはいけない（末尾に足すだけの直しだと流すたびに足し続ける）。
        #   さらに old と new は片方がもう一方の一部になりうる（今回 hd5s_26k1_10 の intro がそうだった：
        #   new が old の先頭と一致していて「すでに直っている」と誤判定した）。
        #   なので判定は「欄丸ごと一致するか」という厳密な形にする。
        if cur == e["new"]:
            skipped.append(label)
            continue

        # その大問の中（intro・question・meaning）でちょうど 1 回だけ出ることを確かめる。
        texts = [x.get("intro", "")]
        for s in x.get("steps", []):
            texts.append(s.get("question", ""))
            texts.append(s.get("meaning", ""))
        n_all = sum(t.count(e["old"]) for t in texts)
        assert n_all == 1, "%s: 置きかえ前の文字列がこの大問の中に %d 回ある（1回でないと当てられない）" % (label, n_all)

        # 欄まるごとの置きかえ。前の状態が想定どおりかを厳しく見る
        # （ここで止まったら、よその直しがすでに入っている可能性がある）。
        assert cur == e["old"], "%s: 欄の中身が想定と違う。手で見てから直すこと" % label
        holder[key] = e["new"]
        done.append(label)

    # svg と answer にさわっていないことの確認（この処理は文字だけを直す）
    for did in sorted(set(e["id"] for e in EDITS)):
        x = by_id[did][0]
        assert "svg" in x, "%s に svg が無い" % did
        for s in x.get("steps", []):
            assert "answer" in s, "%s に answer が無い" % did

    save(path, d)

    print("対象JSON: %s" % path)
    print("直した: %d 件" % len(done))
    for s in done:
        print("  + " + s)
    print("すでに直っていた（スキップ）: %d 件" % len(skipped))
    for s in skipped:
        print("  = " + s)
    print("さわった大問: %d 本" % len(set(e["id"] for e in EDITS)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
