LINE, HI, TX, GRAY = '#4f9eff', '#ffd166', '#c9d4f0', '#9aa3c0'
SHADE = 'rgba(255,209,102,0.22)'


def r(v):
    return round(v, 1) if isinstance(v, float) else v


def t(x, y, s, fill=TX, size=13, anchor="middle", extra=""):
    return '<text x="%s" y="%s" font-size="%s" text-anchor="%s" fill="%s"%s>%s</text>' % (
        r(x), r(y), size, anchor, fill, extra, s)


def ln(x1, y1, x2, y2, stroke=LINE, w=2, dash=None):
    d = ' stroke-dasharray="%s"' % dash if dash else ''
    return '<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="%s"%s/>' % (
        r(x1), r(y1), r(x2), r(y2), stroke, w, d)


def pth(d, stroke=LINE, w=2, fill="none", dash=None):
    ds = ' stroke-dasharray="%s"' % dash if dash else ''
    return '<path d="%s" fill="%s" stroke="%s" stroke-width="%s"%s/>' % (d, fill, stroke, w, ds)


def shade(d):
    return pth(d, stroke=HI, w=2, fill=SHADE)


def dot(x, y, rad=3.5, fill=HI):
    return '<circle cx="%s" cy="%s" r="%s" fill="%s"/>' % (r(x), r(y), rad, fill)


def svg(vb, body):
    return '<svg viewBox="%s" xmlns="http://www.w3.org/2000/svg" %s>%s</svg>' % (vb, S, body)


def dim(x1, y1, x2, y2, label, off=22, side=1, gap=15):
    """2点間の寸法線（両端に短い爪）＋そのまん中にラベル。offは図から離す量。"""
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1
    nx, ny = -dy / L * side, dx / L * side               # 単位法線（ずらす向き）
    ax, ay, bx, by = x1 + nx * off, y1 + ny * off, x2 + nx * off, y2 + ny * off
    tx, ty = nx * 4, ny * 4                              # 爪（法線方向の短い線）
    lx, ly = (ax + bx) / 2 + nx * gap, (ay + by) / 2 + ny * gap + 4
    return "".join([
        ln(ax, ay, bx, by, GRAY, 1.2),
        ln(ax - tx, ay - ty, ax + tx, ay + ty, GRAY, 1.2),
        ln(bx - tx, by - ty, bx + tx, by + ty, GRAY, 1.2),
        t(lx, ly, label, TX, 12),
    ])


def arcmark(cx, cy, rad, a1, a2, label=None, lab_r=None, color=HI):
    """中心(cx,cy)の角の印（小さい弧）＋度数のラベル。a1,a2は数学角（度・反時計回り）"""
    x1, y1 = cx + rad * math.cos(math.radians(a1)), cy - rad * math.sin(math.radians(a1))
    x2, y2 = cx + rad * math.cos(math.radians(a2)), cy - rad * math.sin(math.radians(a2))
    sweep = 0 if a2 > a1 else 1                          # yが下向きなので向きが反転する
    out = pth('M%s %s A%s %s 0 0 %d %s %s' % (r(x1), r(y1), r(rad), r(rad), sweep, r(x2), r(y2)),
              stroke=color, w=1.6)
    if label is not None:
        lr = lab_r if lab_r is not None else rad + 20
        am = math.radians((a1 + a2) / 2.0)
        out += t(cx + lr * math.cos(am), cy - lr * math.sin(am) + 4, label, TX, 12)
    return out


def rightangle(x, y, dx1, dy1, dx2, dy2, s=9):
    """(x,y)の直角記号。dx1..は2辺の向き"""
    def u(a, b):
        L = math.hypot(a, b) or 1
        return a / L * s, b / L * s
    ax, ay = u(dx1, dy1)
    bx, by = u(dx2, dy2)
    return '<path d="M%s %s L%s %s L%s %s" fill="none" stroke="%s" stroke-width="1.4"/>' % (
        r(x + ax), r(y + ay), r(x + ax + bx), r(y + ay + by), r(x + bx), r(y + by), GRAY)


def A(rad, x, y, sweep, large=0):
    return 'A%s %s 0 %d %d %s %s' % (r(rad), r(rad), large, sweep, r(x), r(y))


