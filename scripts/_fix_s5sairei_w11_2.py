def _apply(d, edits, field):
    by_id = {}
    for r in iter_daimon(d, grade="5", app_courses=["sairei"]):
        by_id[r["x"].get("id")] = r["x"]

    applied = already = 0
    for id_, step_i, old, new in edits:
        x = by_id.get(id_)
        if x is None:
            raise SystemExit("id not found: %s" % id_)
        steps = x.get("steps") or []
        if step_i >= len(steps):
            raise SystemExit("step index out of range: %s step%d" % (id_, step_i))
        cur = steps[step_i].get(field)
        if cur == new:
            already += 1
            continue
        if cur != old:
            raise SystemExit(
                "mismatch at %s step%d (%s): current value does not match expected old text.\n"
                "--- current ---\n%s\n--- expected old ---\n%s" % (id_, step_i, field, cur, old)
            )
        steps[step_i][field] = new
        applied += 1
    return applied, already


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE, "data", "hama_daimon.json")

    d = json.load(io.open(target, encoding="utf-8"))

    # 大問idの重複が無いことを先に確認（同じidを2回パッチしていないか）
    seen_pairs = set()
    for id_, step_i, old, new in MEANING_EDITS:
        key = ("meaning", id_, step_i)
        assert key not in seen_pairs, "duplicated MEANING_EDITS entry: %s step%d" % (id_, step_i)
        seen_pairs.add(key)
    for id_, step_i, old, new in QUESTION_EDITS:
        key = ("question", id_, step_i)
        assert key not in seen_pairs, "duplicated QUESTION_EDITS entry: %s step%d" % (id_, step_i)
        seen_pairs.add(key)

    m_applied, m_already = _apply(d, MEANING_EDITS, "meaning")
    q_applied, q_already = _apply(d, QUESTION_EDITS, "question")

    io.open(target, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))
    sys.stdout.write(
        "meaning: applied=%d already=%d total=%d\n"
        "question: applied=%d already=%d total=%d\n"
        "target=%s\n"
        % (m_applied, m_already, len(MEANING_EDITS),
           q_applied, q_already, len(QUESTION_EDITS), target)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
