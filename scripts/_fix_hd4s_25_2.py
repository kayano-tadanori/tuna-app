def main():
    path = os.path.join(G.BASE, "data", "hama_daimon.json")
    d = json.load(io.open(path, encoding="utf-8"))
    hit = done = already = 0
    for r in G.iter_daimon(d):
        x = r["x"]
        if x["id"] != "hd4s_25_2":
            continue
        hit += 1
        for no, fld, old, new in FIX:
            s = x["steps"][no - 1]
            cur = s.get(fld) or ""
            # ★欄まるごとの一致で判定する（→method_kansa_pipeline の冪等の罠）
            if cur == new:
                already += 1
            elif cur == old:
                s[fld] = new
                done += 1
            else:
                print("  ⚠ 小問%d の%s が想定と違う: %r" % (no, fld, cur[:60]))
    assert hit == 1, "hd4s_25_2 が %d本みつかった（想定は1本）" % hit
    io.open(path, "w", encoding="utf-8", newline="\n").write(
        json.dumps(d, ensure_ascii=False, indent=1) + "\n")
    print("直した欄 %d ／ すでに直っていた %d" % (done, already))


if __name__ == "__main__":
    main()
