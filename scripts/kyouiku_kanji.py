# 手入力のゆらぎを掃除（ローマ字が混じっていないか等）
import re as _re
_G5 = _re.sub(r"[^一-鿿]", "", G5)

GRADE = {}
for _g, _s in ((1, G1), (2, G2), (3, G3), (4, G4), (5, _G5), (6, G6)):
    for _c in _s:
        GRADE.setdefault(_c, _g)

def kanji_grade(ch):
    """その漢字を習う学年。小学校で習わない漢字は 7 を返す。"""
    return GRADE.get(ch, 7)

def word_level(word):
    """語を書くのに必要な最高学年。漢字が無ければ 0。"""
    ks = [c for c in word if "一" <= c <= "鿿"]
    return max((kanji_grade(c) for c in ks), default=0)

