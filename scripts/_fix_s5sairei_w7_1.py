def _cross(p, q, r, s):
    """線分pq と 線分rs の交点（無限直線として）。"""
    (x1, y1), (x2, y2), (x3, y3), (x4, y4) = p, q, r, s
    d = (x2 - x1) * (y4 - y3) - (y2 - y1) * (x4 - x3)
    t = ((x3 - x1) * (y4 - y3) - (y3 - y1) * (x4 - x3)) / d
    return (x1 + t * (x2 - x1), y1 + t * (y2 - y1))


def _near(a, b, tol=0.06):
    return abs(a - b) <= tol


def verify_geometry():
    """これから書きこむ図の座標が、問題文の数値と本当に合うか確かめる。"""
