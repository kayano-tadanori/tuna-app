def keta_bunkai(n, base):
    u"""n を base 進法にするわり算を、子どもが書くとおりに並べた文字列を返す。"""
    seq, cur, out = [], n, []
    while True:
        q, r = cur // base, cur % base
        out.append(u"%d÷%d＝%dあまり%d" % (cur, base, q, r))
        seq.append(str(r))
        cur = q
        if cur == 0:
            break
    return u"、".join(out), u"".join(reversed(seq))


