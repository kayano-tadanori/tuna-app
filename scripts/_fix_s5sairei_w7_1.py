    if not _near((B[1] - A[1]) / S, 30): bad.append("7127(1) AB != 30cm")
    if not _near((C[0] - B[0]) / S, 40): bad.append("7127(1) BC != 40cm")
    if not _near((Fp[1] - D[1]) / S, 15): bad.append("7127(1) DF != 15cm")
    if not _near((Fp[0] - E[0]) / S, 36): bad.append("7127(1) EF != 36cm")
    if not _near((C[0] - E[0]) / S, 24): bad.append("7127(1) EC != 24cm")
    p = _cross(A, C, D, E)
    if not _near((300 - p[1]) / S, 45.0 / 7): bad.append("7127(1) x != 45/7")
    if not (_near(p[0], 301.4, 0.1) and _near(p[1], 248.6, 0.1)):
        bad.append("7127(1) x印の座標ちがい %r" % (p,))

    # --- HG-7127 (2) 新しく作る図 --------------------------------------------
    E2, D2, F2, C2, A2 = (178, 300), (490, 300), (443.8, 189.2), (370, 300), (50, 60)
    ef = ((F2[0] - E2[0]) ** 2 + (F2[1] - E2[1]) ** 2) ** 0.5
    fd = ((D2[0] - F2[0]) ** 2 + (D2[1] - F2[1]) ** 2) ** 0.5
    ed = D2[0] - E2[0]
