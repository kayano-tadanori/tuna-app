def set_field(did, obj, key, old, new, tag):
    u"""欄まるごとの一致で判定＝冪等。"""
    cur = obj.get(key)
    if cur == new:
        return
    assert cur == old, u"%s の %s が想定と違う\n  今: %r\n  想定: %r" % (did, tag, cur, old)
    obj[key] = new
    changed.append((did, tag))


def svg_add(did, obj, addition, marker, tag):
    u"""図SVGの </svg> の直前に足す。marker があれば済んでいるので飛ばす。"""
    s = obj.get("svg") or ""
    if marker in s:
        return
    assert s.count(u"</svg>") == 1, u"%s の %s に </svg> が1つでない" % (did, tag)
    obj["svg"] = s.replace(u"</svg>", addition + u"</svg>")
    changed.append((did, tag))


def add_step(did, x, step, tag):
    u"""小問を1つ足す。同じ設問があれば飛ばす（冪等）。"""
    for s in x["steps"]:
        if s.get("question") == step["question"]:
            return
    x["steps"].append(step)
    changed.append((did, tag))


