    r = [af, ag - af, ah - ag]
    u = r[0] / 3.0
    if not (_near(r[0] / u, 3, 0.01) and _near(r[1] / u, 5, 0.01) and _near(r[2] / u, 4, 0.01)):
        bad.append("7180 AF:FG:GH != 3:5:4 (%r)" % (r,))

    # --- HG-7147 図に足す P ---------------------------------------------------
    S4 = 300 / 12.0                        # 正方形の一辺 300px = 12cm
    if not _near((350 - 200) / S4, 6): bad.append("7147 PB != 6cm")

    return bad


