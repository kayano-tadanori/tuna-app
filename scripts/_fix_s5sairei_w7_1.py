    if abs(dot) > 40: bad.append("7127(2) Fが直角でない (naiseki=%.2f)" % dot)
    p2 = _cross(A2, C2, E2, F2)
    if not _near((300 - p2[1]) / S, 45.0 / 7, 0.01): bad.append("7127(2) x != 45/7")
    if not (_near(p2[0], 301.4, 0.2) and _near(p2[1], 248.6, 0.2)):
        bad.append("7127(2) x印の座標ちがい %r" % (p2,))

