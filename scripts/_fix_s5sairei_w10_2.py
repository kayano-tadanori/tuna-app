# ---------------------------------------------------------------- 小問の追加
# (大問id, 追加前に想定する小問数, 追加する小問dict)
# 冪等判定は「同じquestion文の小問が既にあるか」で行う。
ADD_STEPS = [
 ('hd5s_25k2_15', 2, {
   "question": "この列車の長さは何mですか。",
   "answer": "144",
   "meaning": "①列車の時速は70.2km/時。バイクとの相対の速さ(列車−27)は70.2－27＝43.2km/時。②43.2km/時を秒速に直すと、43.2×1000÷3600＝12m/秒。③バイクを追いこすのにかかった12秒をかけて、列車の長さ＝12×12＝144m。",
 }),
]


def dig(x, path):
    node = x
    for p in path[:-1]:
        node = node[p] if isinstance(p, int) else node[p]
    return node, path[-1]


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE, "data", "hama_daimon.json")

    d = json.load(io.open(target, encoding="utf-8"))

    # 対象の大問を iter_daimon だけで引く
    want = set(p[0] for p in PATCHES) | set(a[0] for a in ADD_STEPS)
    found = {}
    for r in iter_daimon(d):
        x = r["x"]
        if x.get("id") in want:
            assert x["id"] not in found, "daimon id duplicated: " + x["id"]
            found[x["id"]] = x
    missing = want - set(found)
    assert not missing, "daimon not found: " + ", ".join(sorted(missing))

    changed = skipped = 0

    for did, path, old, new in PATCHES:
        x = found[did]
        node, key = dig(x, path)
        cur = node[key]
        if cur == new:          # 冪等：すでに直っている
            skipped += 1
            continue
        assert cur == old, "%s %s: old value differs (another session wrote it?)" % (did, "/".join(map(str, path)))
        node[key] = new
        changed += 1

    for did, expect_len, new_step in ADD_STEPS:
        x = found[did]
        steps = x["steps"]
        if any(s.get("question") == new_step["question"] for s in steps):
            skipped += 1          # 冪等：すでに追加ずみ
            continue
        assert len(steps) == expect_len, "%s: step count differs (another session wrote it?) got=%d want=%d" % (did, len(steps), expect_len)
        steps.append(dict(new_step))
        changed += 1

    io.open(target, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))
    sys.stdout.write("changed=%d  skipped(already-fixed)=%d  target=%s\n" % (changed, skipped, target))
    return 0


if __name__ == "__main__":
    sys.exit(main())
