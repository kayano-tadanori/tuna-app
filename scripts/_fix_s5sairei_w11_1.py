def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE, "data", "hama_daimon.json")
    text = io.open(path, encoding="utf-8").read()
    d = json.loads(text)

    changed = False
    applied, already, problems = [], [], []

    for id_, (want_hg, step_fixes) in FIXES.items():
        hits = [r for r in genbo_common.iter_daimon(d) if r["x"].get("id") == id_]
        if len(hits) != 1:
            problems.append(u"%s: iter_daimon で %d件ヒット（1件のはず）" % (id_, len(hits)))
            continue
        x = hits[0]["x"]
        if x.get("hg") != want_hg:
            problems.append(u"%s: hg欄が想定と違う（想定=%s 実際=%s）" % (id_, want_hg, x.get("hg")))
            continue
        steps = x.get("steps") or []
        for step_idx, old, new in step_fixes:
            if step_idx >= len(steps):
                problems.append(u"%s: steps[%d] が存在しない（steps数=%d）" % (id_, step_idx, len(steps)))
                continue
            cur = steps[step_idx].get("meaning")
            tag = "%s[step%d]" % (id_, step_idx)
            if cur == new:
                already.append(tag)
            elif cur == old:
                steps[step_idx]["meaning"] = new
                changed = True
                applied.append(tag)
            else:
                problems.append(u"%s: steps[%d]['meaning'] が想定の新旧どちらとも一致しない:\n  現在=%r"
                                 % (id_, step_idx, cur))

    if problems:
        sys.stderr.write(u"\n".join(problems) + u"\n")
        raise SystemExit(u"%d件の不一致があるため、1件も書き込まずに中止しました。" % len(problems))

    print(u"適用: %d件 %s" % (len(applied), applied))
    print(u"既に適用済み(スキップ): %d件 %s" % (len(already), already))

    if changed:
        out = json.dumps(d, ensure_ascii=False, indent=1)
        io.open(path, "wb").write(out.encode("utf-8"))
        print(u"書き込み完了: %s" % path)
    else:
        print(u"変更なし（すべて適用済み）のため書き込みなし: %s" % path)


if __name__ == "__main__":
    main()
