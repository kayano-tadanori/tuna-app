# ============================================================ 図の検算（HG-3675）
# 原本 `浜問題\5年算数最レ\5年_小5最レ算数_第3分冊_第1講座.pdf` の本文p21（PDF20ページ目）を
# 212dpiで書き出して確認したところ、現物の図でも 60° の印は「角COD」に付いていて、
# 問題文だけが「おうぎ形OBAの中心角は60度」と言っている。つまりアプリの図は現物どおりで正しい。
# 直すのは、アプリが独自に足した図の下の注記（印が角AOBのことだと読めてしまう）だけ。
ZU_3675 = {
    "O": (210.0, 200.0), "A": (30.0, 200.0), "B": (120.0, 44.1),
    "C": (135.7, 149.2), "D": (216.8, 110.3),
    # 図に描いてある60°の印（弧）の両はし
    "mark1": (212.9, 162.1), "mark2": (178.6, 178.6),
}


def _ang(o, p):
    """oから見たpの向き（度・反時計まわり。SVGはy下向きなので上下を入れかえる）。"""
    return math.degrees(math.atan2(o[1] - p[1], p[0] - o[0])) % 360.0


def verify_zu(log):
    z = ZU_3675
    O = z["O"]
    a = {k: _ang(O, z[k]) for k in ("A", "B", "C", "D", "mark1", "mark2")}
    r = {k: math.hypot(z[k][0] - O[0], z[k][1] - O[1]) for k in ("A", "B", "C", "D")}
    aob = (a["A"] - a["B"]) % 360.0
    cod = (a["C"] - a["D"]) % 360.0
    log("  図の検算 HG-3675: 角AOB=%.2f度 角COD=%.2f度 / 半径 OA=%.1f OB=%.1f OC=%.1f OD=%.1f"
        % (aob, cod, r["A"], r["B"], r["C"], r["D"]))
    assert abs(aob - 60.0) < 0.2, "角AOBが60度でない: %.3f" % aob
    assert abs(cod - 60.0) < 0.2, "角CODが60度でない: %.3f" % cod
    assert abs(r["A"] - 180.0) < 0.5 and abs(r["B"] - 180.0) < 0.5, "A・Bが半径60cmの円周上にない"
    assert abs(r["C"] - 90.0) < 0.5 and abs(r["D"] - 90.0) < 0.5, "C・Dが半径30cmの円周上にない"
    # 60°の印が「角COD」に付いていること（角AOBではない）を数値で確かめる
    assert abs(a["mark1"] - a["D"]) < 1.0, "60°の印のはしがODの向きでない: %.2f vs %.2f" % (a["mark1"], a["D"])
    assert abs(a["mark2"] - a["C"]) < 1.0, "60°の印のはしがOCの向きでない: %.2f vs %.2f" % (a["mark2"], a["C"])
    log("  → 60°の印は角COD（角AOBではない）。注記の文だけを直す。")
    # A・C・D が一直線であることも確かめておく（問題文の「ACとCDは一直線」）
    cr = ((z["C"][0] - z["A"][0]) * (z["D"][1] - z["A"][1])
          - (z["C"][1] - z["A"][1]) * (z["D"][0] - z["A"][0]))
    assert abs(cr) < 60.0, "A・C・Dが一直線でない（外積 %.1f）" % cr


