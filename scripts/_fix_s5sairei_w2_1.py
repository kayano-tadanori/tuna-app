def _get_holder(x, path):
    """パス（"svg" / "intro" / "steps/2/meaning"）から (入れ物dict, キー) を返す。"""
    parts = path.split("/")
    if len(parts) == 1:
        return x, parts[0]
    assert parts[0] == "steps" and len(parts) == 3, "パスの形がおかしい: " + path
    i = int(parts[1])
    steps = x.get("steps") or []
    assert i < len(steps), "小問 %d が無い（%s）" % (i, path)
    return steps[i], parts[2]


def apply_edits(x, edits, log):
    changed = 0
    for kind, path, old, new in edits:
        holder, key = _get_holder(x, path)
        cur = holder.get(key, "")
        assert isinstance(cur, str), "文字列でない項目は触らない: " + path

        if kind == "R":
            # 置きかえ後がもとの文字列を含む「書き足し型」は2回目も old が見つかる。
            # 先に「もう入っているか」を見てから止める。
            if new in cur and (old not in cur or old in new):
                continue
            if old not in cur:
                assert new in cur, "%s: もとの文字列も置きかえ後も見つからない → %r" % (path, old[:40])
                continue
            n = cur.count(old)
            assert n == 1, "%s: アンカーが %d 回出る（1回でないので置きかえない）→ %r" % (path, n, old[:40])
            holder[key] = cur.replace(old, new)
            changed += 1
        elif kind == "SET":
            if cur == new:
                continue                       # すでに直っている
            assert old in cur, "%s: 目じるし %r が見つからない（もう別物になっている）" % (path, old[:40])
            assert cur.count(old) == 1, "%s: 目じるしが2回以上出る → %r" % (path, old[:40])
            holder[key] = new
            changed += 1
        else:
            raise AssertionError("知らない種類: " + kind)
    return changed


def main(argv):
    path = os.path.abspath(argv[1] if len(argv) > 1 else DEFAULT_JSON)

    def log(s):
        sys.stdout.write(s + "\n")

    log("対象: " + path)
    verify_zu(log)

    raw = io.open(path, "rb").read()
    assert b"\r" not in raw, "対象JSONにCRが混ざっている（改行がCRLFになっている）"
    d = json.loads(raw.decode("utf-8"))

    index = {}
    for rec in iter_daimon(d):          # ★走査はここだけ（自前で入れ子を歩かない）
        y = rec["x"]
        i = y.get("id") if isinstance(y, dict) else None
        if i:
            index.setdefault(i, []).append(y)

    total = 0
    touched = []
    for did, edits in EDITS:
        hits = index.get(did) or []
        assert len(hits) == 1, "%s が %d 件見つかった（1件でないので止める）" % (did, len(hits))
        c = apply_edits(hits[0], edits, log)
        total += c
        if c:
            touched.append((did, hits[0].get("hg", "?"), c))
            log("  直した %s（%s）: %d か所" % (did, hits[0].get("hg", "?"), c))
        else:
            log("  そのまま %s（%s）: すでに直っている" % (did, hits[0].get("hg", "?")))

    if total == 0:
        log("変更なし。ファイルは書きかえない。")
        return 0

    # ★書き出しはバイトで（"w" は Windows で改行が CRLF に化ける）
    out = (json.dumps(d, ensure_ascii=False, indent=1) + "\n").encode("utf-8")
    with io.open(path, "wb") as f:
        f.write(out)

    log("---- 書きこみ完了: 大問 %d本 / %d か所" % (len(touched), total))
    log("     " + "、".join("%s(%s)" % (i, h) for i, h, _ in touched))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
