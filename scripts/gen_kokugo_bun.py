def bunzu(rows):
    """文図をHTMLで組む。rows = [(深さ, [はこの文字列, ...]), ...]"""
    html = ['<div class="bunzu"><div class="bz-cap">文図</div>']
    labeled = False
    for depth, boxes in rows:
        cls = 'bz-l%d' % depth
        cells = ''
        for b in boxes:
            if b == '→':                      # 矢印ははこにしない
                cells += '<span class="bz-ar">─→</span>'
            else:
                cells += '<span class="bz-box%s">%s</span>' % (' bz-blank' if b == '①' else '', b)
        if depth == 1:
            html.append('<div class="%s"><span class="bz-lab">主語</span>%s<span class="bz-lab">じゅつ語</span></div>' % (cls, cells))
        else:
            # ★はじめの枝にだけ「上のはこをくわしくすることば」と書いておく。
            #   これが無いと、下の段が主語にかかっているように見える
            note = ''
            if depth == 2 and not labeled:
                note = '<span class="bz-lab">じゅつ語をくわしくすることば</span>'
                labeled = True
            html.append('<div class="%s"><span class="bz-ar">└</span>%s%s</div>' % (cls, cells, note))
    html.append('</div>')
    return ''.join(html)


