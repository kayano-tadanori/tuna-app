def build():
    out = []
    for i, (unit, src, q, ans, ch, mean, diff) in enumerate(Q, 1):
        out.append({
            'id': 'kb%03d' % i,
            'question': q,
            'answer': ans,
            'choices': ch,
            'meaning': mean,
            'unit': unit,
            'grade': 3,
            'difficulty': diff,
            'src': src,
        })
    return out


def check(data):
    errs = []
    seen_q, seen_id = {}, set()
    for r in data:
        rid = r['id']
        if rid in seen_id:
            errs.append('%s: IDが重複' % rid)
        seen_id.add(rid)
        # ①答えが選択肢にあるか
        if r['answer'] not in r['choices']:
            errs.append('%s: 答えが選択肢に無い（%s）' % (rid, r['answer']))
        # ②選択肢の数・重複
        if len(r['choices']) != 4:
            errs.append('%s: 選択肢が4つでない（%d）' % (rid, len(r['choices'])))
        if len(set(r['choices'])) != len(r['choices']):
            errs.append('%s: 選択肢が重複' % rid)
        # ③解説の結びと答えの表記ずれ
        if r['answer'] not in r['meaning']:
            errs.append('%s: 解説に答えの表記が無い' % rid)
        if not r['meaning'].endswith('です。'):
            errs.append('%s: 解説が「です。」で終わっていない' % rid)
        # ④問題文の重複（図ちがいは別問題なので図もふくめて比べる）
        if r['question'] in seen_q:
            errs.append('%s: 問題文が %s と同じ' % (rid, seen_q[r['question']]))
        seen_q[r['question']] = rid
        # ⑤unit・grade・difficulty
        if r['unit'] not in (U_KOSO, U_SHUGO, U_SHUSHOKU, U_BUNZU):
            errs.append('%s: 単元名が表に無い（%s）' % (rid, r['unit']))
        if r['difficulty'] not in (1, 2, 3, 4):
            errs.append('%s: 難易度が1〜4でない' % rid)
        # ⑥HTMLタグの対応
        q = r['question']
        if q.count('<div') != q.count('</div>') or q.count('<span') != q.count('</span>'):
            errs.append('%s: HTMLタグが対応していない' % rid)
        if re.search(r'<(?!/?(div|span|br)\b)', q):
            errs.append('%s: 想定外のHTMLタグ' % rid)

    # ⑦学年×難易度の0問セル（小3のd1〜d4が10問以上あるか）
    for d in (1, 2, 3, 4):
        n = len([r for r in data if r['grade'] == 3 and r['difficulty'] == d])
        if n < 10:
            errs.append('小3 難易度%d が %d問（10問未満）' % (d, n))
    return errs


