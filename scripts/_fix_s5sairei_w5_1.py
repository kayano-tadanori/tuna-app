def _arc_points(p0, p1, r, large, sweep, n=4000):
    """SVGの円弧を折れ線にほどく（rx＝ry・回転0 のものだけ扱う）。"""
    (x0, y0), (x1, y1) = p0, p1
    mx, my = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    dx, dy = x1 - x0, y1 - y0
    d = math.hypot(dx, dy)
    h = math.sqrt(max(r * r - (d / 2.0) ** 2, 0.0))
    ux, uy = -dy / d, dx / d
    cx, cy = (mx + h * ux, my + h * uy) if (large != sweep) else (mx - h * ux, my - h * uy)
    a1 = math.atan2(y0 - cy, x0 - cx)
    a2 = math.atan2(y1 - cy, x1 - cx)
    if sweep == 1:
        while a2 < a1:
            a2 += 2 * math.pi
    else:
        while a2 > a1:
            a2 -= 2 * math.pi
    return [(cx + r * math.cos(a1 + (a2 - a1) * i / n),
             cy + r * math.sin(a1 + (a2 - a1) * i / n)) for i in range(1, n + 1)]


def path_area_px2(dattr):
    """M / L / A / Z だけの path が囲む面積（px²）。"""
    toks = re.findall(r"[MLAZmlaz]|[-+]?\d*\.?\d+", dattr)
    pts, i, cur = [], 0, None
    while i < len(toks):
        c = toks[i]
        if c in "MmLl":
            cur = (float(toks[i + 1]), float(toks[i + 2]))
            pts.append(cur)
            i += 3
        elif c in "Aa":
            r = float(toks[i + 1])
            large, sweep = int(float(toks[i + 4])), int(float(toks[i + 5]))
            nxt = (float(toks[i + 6]), float(toks[i + 7]))
            pts.extend(_arc_points(cur, nxt, r, large, sweep))
            cur = nxt
            i += 8
        elif c in "Zz":
            i += 1
        else:
            raise ValueError("path に未対応のコマンド: %r" % c)
    s = 0.0
    for k in range(len(pts)):
        x1, y1 = pts[k]
        x2, y2 = pts[(k + 1) % len(pts)]
        s += x1 * y2 - x2 * y1
    return abs(s) / 2.0


def check_svg(did, svg):
    """入れようとしている図SVGが問題文の答えと合うかを座標から確かめる。"""
    spec = SVG_CHECK[did]
    for m in spec["must_contain"]:
        if m not in svg:
            return False, "図に %r が見あたらない" % m
    m = re.search(r'<path d="([^"]+)"[^>]*fill="rgba\(255,209,102', svg)
    if not m:
        return False, "斜線部（黄色でぬる path）が見あたらない"
    area = path_area_px2(m.group(1)) / (spec["px_per_cm"] ** 2)
    if abs(area - spec["expect_cm2"]) > spec["tol"]:
        return False, "斜線部の面積が %.4fcm²。%.4fcm² のはずなので入れない" % (area, spec["expect_cm2"])
    return True, "斜線部の面積 %.4fcm²（円周率3.14なら64.5cm²）＝問題文の答えと一致" % area


