def main():
    path = os.path.join(G.BASE, "data", "hama_daimon.json")
    d = json.load(io.open(path, encoding="utf-8"))
    done = already = miss = 0
    for r in G.iter_daimon(d):
        x = r["x"]
        if x["id"] not in FIX:
            continue
        for no, old, new in FIX[x["id"]]:
            s = x["steps"][no - 1]
            cur = s.get("meaning") or ""
            # ★欄まるごとの一致で判定（→method_kansa_pipeline の冪等の罠）
            if cur == new:
                already += 1
            elif cur == old:
                s["meaning"] = new
                done += 1
            else:
                miss += 1
                print("  ⚠ %s 小問%d が想定と違う: %r" % (x["id"], no, cur[:50]))
    io.open(path, "w", encoding="utf-8", newline="\n").write(
        json.dumps(d, ensure_ascii=False, indent=1) + "\n")
    print("厚くした %d ／ すでに済み %d ／ 見つからず %d" % (done, already, miss))


if __name__ == "__main__":
    main()
