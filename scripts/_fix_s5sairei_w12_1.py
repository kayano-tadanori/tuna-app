def find_one(d, target_id):
    hits = [rec["x"] for rec in iter_daimon(d) if rec["x"].get("id") == target_id]
    if len(hits) != 1:
        raise SystemExit(f"[ABORT] {target_id}: 大問が{len(hits)}件見つかった（1件のはず）。何も書かない")
    return hits[0]


def keyed_steps(x, target_id, key_fn):
    """steps の各要素に key_fn(question)->key を当てて {key: step} を作る。
    1つの大問の中でキーが重複したり漏れたりしたら止める。"""
    steps = x.get("steps")
    out = {}
    for s in steps:
        k = key_fn(s["question"])
        if k is None:
            raise SystemExit(f"[ABORT] {target_id}: 設問文からキーを特定できない小問がある。何も書かない\n  q={s['question']!r}")
        if k in out:
            raise SystemExit(f"[ABORT] {target_id}: キー'{k}'が複数の小問に一致した。何も書かない")
        out[k] = s
    return out


def apply_patch(d, target_id, key_fn, order, new_meanings):
    """key_fn で各小問を識別し、order の順に並べ替えて meaning だけ new_meanings に
    差し替える。question/answer/choices は元の値をそのまま使う（書き写さない）。"""
    x = find_one(d, target_id)
    by_key = keyed_steps(x, target_id, key_fn)
    if set(by_key) != set(order):
        raise SystemExit(f"[ABORT] {target_id}: 想定したキー集合と食い違う。何も書かない\n"
                          f"  期待={sorted(order)} 実際={sorted(by_key)}")

    new_steps = []
    for k in order:
        s = dict(by_key[k])  # 元の question/answer/choices等はコピーして保持
        s["meaning"] = new_meanings[k]
        new_steps.append(s)

    if x.get("steps") == new_steps:
        print(f"[skip] {target_id}: 既に修正済み")
        return False

    # 未修正のサイン＝現在の全小問の meaning が「まったく同じ1つの長文」であること。
    cur_meanings = [s["meaning"] for s in x["steps"]]
    if len(set(cur_meanings)) != 1:
        raise SystemExit(f"[ABORT] {target_id}: 現在のmeaningが想定(全小問で同一文)と食い違う。何も書かない")

    x["steps"] = new_steps
    print(f"[fix]  {target_id}: steps を差し替え（{len(order)}小問）")
    return True


def apply_svg_fix(d, target_id, old_marker, new_marker):
    x = find_one(d, target_id)
    svg = x.get("svg", "")
    if new_marker in svg and old_marker not in svg:
        print(f"[skip] {target_id}.svg: 既に修正済み")
        return False
    cnt = svg.count(old_marker)
    if cnt != 1:
        raise SystemExit(f"[ABORT] {target_id}.svg: 目印'{old_marker}'が{cnt}回見つかった（1回のはず）。何も書かない")
    x["svg"] = svg.replace(old_marker, new_marker)
    print(f"[fix]  {target_id}.svg: 「北」ラベルの位置を図の近くへ修正")
    return True


