def _apply(d):
    by_id = {}
    for r in iter_daimon(d, grade="3", app_courses=["master_bunsatsu"]):
        by_id[r["x"].get("id")] = r["x"]

    applied = already = 0
    for id_, step_i, old, new in MEANING_EDITS:
        x = by_id.get(id_)
        if x is None:
            raise SystemExit("id not found: %s" % id_)
        steps = x.get("steps") or []
        if step_i >= len(steps):
            raise SystemExit("step index out of range: %s step%d" % (id_, step_i))
        cur = steps[step_i].get("meaning")
        if cur == new:
            already += 1
            continue
        if cur != old:
            raise SystemExit(
                "mismatch at %s step%d (meaning): current value does not match expected old text.\n"
                "--- current ---\n%s\n--- expected old ---\n%s" % (id_, step_i, cur, old)
            )
        steps[step_i]["meaning"] = new
        applied += 1
    return applied, already


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BASE, "data", "hama_daimon.json")

    d = json.load(io.open(target, encoding="utf-8"))

    # (id, step index) の重複が無いことを先に確認（同じ箇所を2回パッチしていないか）
    seen = set()
    for id_, step_i, old, new in MEANING_EDITS:
        key = (id_, step_i)
        assert key not in seen, "duplicated MEANING_EDITS entry: %s step%d" % (id_, step_i)
        seen.add(key)

    applied, already = _apply(d)

    io.open(target, "wb").write(json.dumps(d, ensure_ascii=False, indent=1).encode("utf-8"))
    sys.stdout.write(
        "meaning: applied=%d already=%d total=%d\ntarget=%s\n"
        % (applied, already, len(MEANING_EDITS), target)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
