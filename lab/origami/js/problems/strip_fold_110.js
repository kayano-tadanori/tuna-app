// ============================================================
// problems/strip_fold_110.js — 平面図形テキスト「5」（灘中対策コーナー）
//
//   長方形（細長い帯）の紙を1回折ったときの角アの大きさを求める。答え：ア=110°
//
//   ★前のセッションでは「折り目の向き（左上→右下か左下→右上か）とアの位置が確定できない」
//     として見送っていた問題（[[origami_mondai_genbo]]の健康診断）。
//     2026-09-01に**解答ページ(05.pdf p03)の図と式まで600dpiで読み直して確定した**：
//       ・折り目は「下の辺の点Pから右上へ」。40°は折り目そのものではなく、
//         **折り返された下の辺**ともとの下の辺のあいだの角
//       ・折り目は角を2等分するので イ=(180-40)÷2=70°
//       ・ア＝360-(70+90×2)=110°（もとの紙の右の部分がつくる四角形の内角の和）
//     問題ページだけを見て「折り目が40°」と読むと、折り返した紙が下へ行ってしまい
//     図とまったく合わなくなる（実際に鏡映で計算して確かめた）。
//
//   独立検算（答えを使わず与件だけから／scratchpad/ori/verify_new7.py）：
//     ・折り目の傾き = (180-40)/2 = 70° ✓
//     ・折り目PQと上の辺のなす角 = 110.000° ✓（印刷解答と一致）
//     ・帯の右はしまでを 6÷sin40° = 9.3343cm にすると、折り返した右下の角が
//       ちょうど上の辺の上にのる＝原本の図と同じ見え方になる ✓
//
//   座標系：帯の中心を原点に。帯は縦6cm（z=-3〜3）、横は左右とも9.3343cm。
//     P(0,-3)＝折り目の下のはし、Q(2.1838,3)＝折り目の上のはし
// ============================================================
'use strict';

window.ORIGAMI_PROBLEMS = window.ORIGAMI_PROBLEMS || {};

(function () {
  const H = 6;                                   // 帯のはば
  const hz = H / 2;
  const CREASE = 70 * Math.PI / 180;             // 折り目の傾き（(180-40)÷2）
  const Qx = H / Math.tan(CREASE);               // 折り目の上のはしのx（=2.18380）
  const Rx = H / Math.sin(40 * Math.PI / 180);   // 帯の右はしまで（=9.33430）

  ORIGAMI_PROBLEMS.strip_fold_110 = {
    id: 'strip_fold_110',
    name: '帯を1回折る：角アは何度？',
    year: null, school: '平面図形テキスト',
    examType: 'practice',
    nadaGroup: 'fold',
    category: 'fold-angle',
    // 折り返しの合同→折り目が角を2等分→四角形の内角の和（3段）
    difficulty: 3,
    promptText:
      '右の図のように長方形の紙を折ったときの角アの大きさを求めなさい。'
      + '（右はしをつまんで折ってみましょう。折り目の両はしをP・Qとしています）',
    mesh: {
      flatStack: true,
      verts: [
        // パネル0（固定側＝折り目より左）BL・P・Q・TL
        [-Rx, 0, -hz], [0, 0, -hz], [Qx, 0, hz], [-Rx, 0, hz],
        // パネル1（動く側＝折り目より右）P・BR・TR・Q
        [0, 0, -hz], [Rx, 0, -hz], [Rx, 0, hz], [Qx, 0, hz],
      ],
      tris: [
        [0, 1, 2], [0, 2, 3],
        [4, 5, 6], [4, 6, 7],
      ],
      // 帯ぜんたいを0〜1にマップ（u=(x+Rx)/(2Rx), v=(z+hz)/H）
      uv: [
        [0, 0], [0.5, 0], [(Qx + Rx) / (2 * Rx), 1], [0, 1],
        [0.5, 0], [1, 0], [1, 1], [(Qx + Rx) / (2 * Rx), 1],
      ],
      panel: [0, 0, 0, 0, 1, 1, 1, 1],
      boneParent: [-1, 0],
      hinge: [
        null,
        // origin=P、axis=P→Q。外積のY成分 uz*vx-ux*vz = +8.77 > 0 ＝谷折り
        // （つまむ点＝右下の角がまず上へ持ち上がる向き。作問ルール§12）
        { origin: [0, 0, -hz], axis: OGL.vecNorm([Qx, 0, H]) },
      ],
    },
    // 折って左上へ行ってしまった「もとの右半分の輪郭」を破線で残す。
    // アの角の2辺のうち「上の辺を右へ行く向き」はここでしか見えない（作問ルール§10-2）
    previewCreases: [
      { boneId: 0, a: [Qx, 0, hz], b: [Rx, 0, hz], kind: 'outline', afterFold: 1 },   // もとの上の辺
      { boneId: 0, a: [Rx, 0, hz], b: [Rx, 0, -hz], kind: 'outline', afterFold: 1 },  // もとの右はし
      { boneId: 0, a: [Rx, 0, -hz], b: [0, 0, -hz], kind: 'outline', afterFold: 1 },  // もとの下の辺
    ],
    steps: [
      {
        id: 1,
        handle: { boneId: 1, local: [Rx, 0, -hz] }, // 右下の角をつまむ
        targetAngle: Math.PI, snapDeg: 0.3, returnAngle: 0,
        hintLabel: '折り目PQで、右半分を左上へ折り返す（右下の角がちょうど上の辺にのる）',
        creaseLine: { boneId: 0, a: [0, 0, -hz], b: [Qx, 0, hz], kind: 'valley' },
      },
    ],
    labelPoints: [
      { boneId: 0, local: [0, 0, -hz], label: 'P' },
      { boneId: 0, local: [Qx, 0, hz], label: 'Q' },
    ],
    angleMarks: [
      // 与えられている40°：もとの下の辺（左向き）と、折り返された下の辺のあいだ。
      // 折り終わってからだけ出す（途中の角度は40°ではないため）
      {
        boneId: 0, vertex: [0, 0, -hz], from: [-4, 0, -hz],
        to: [Rx, 0, -hz], toBone: 1, label: '40°', radius: 1.5, atTarget: 1,
      },
      // 求める角ア：折り目QPと、もとの上の辺を右へ行く向きのあいだ
      {
        boneId: 0, vertex: [Qx, 0, hz], from: [0, 0, -hz], to: [Rx, 0, hz],
        label: 'ア', radius: 1.8, atTarget: 1,
      },
    ],
    answer: { value: 110, display: '110', unit: '度', tolerance: 0.5 },
    explanation: [
      '紙を折り返しても形と大きさは変わらないので、折り返した部分ともとの部分は合同。だから折り目は、もとの下の辺と、折り返された下の辺がつくる角を、ちょうど半分ずつに分けている。',
      '点Pのまわりを見ると、下の辺（左向き）から折り返された下の辺までが40°。残りの角は180°-40°=140°で、折り目がそれを半分に分けるので70°ずつ。',
      'つまり、折り目PQと、もとの下の辺（右向き）とのあいだの角が70°。',
      'ここで、折る前の「右半分の紙」を四角形として見る。4つの角は、Pのところが70°、右上と右下は長方形の角なので90°ずつ、そしてQのところが角ア。',
      '四角形の内角の和は360°なので、ア＝360°-(70°+90°+90°)＝110°。',
    ],
  };
})();
