//   かぶと 7手。★おりがみくらぶの折り図をそのまま実測して組んだ
//   （https://www.origami-club.com/fun/kabuto/zu.gif の破線を画像から測った）。
//
//   1. まんなかで半分に折る（とがった所が下の三角）
//   2-3. 左右の角を、下のとがった所へ折る → ひし形
