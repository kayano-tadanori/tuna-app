// works/patocar.js — パトカー
//   ぱとかー 6手。★おりがみくらぶ easy/vehicle/Patrol の折り図を実測。
//   ① たてよこ半分に折り目をつけてもどす
//   ② 下のふちを、まん中の線に合わせて**後ろへ**折り上げる
